import Foundation
import Testing
@testable import Mantel

private let start = Date(timeIntervalSince1970: 1_800_000_000)
private func at(_ seconds: TimeInterval) -> Date { start.addingTimeInterval(seconds) }
private let text = ["public.utf8-plain-text"]

@Test func newestCopyComesFirst() {
    var history = ClipboardHistory()
    history.record("first", types: text, at: at(0))
    history.record("second", types: text, at: at(10))
    #expect(history.items.map(\.text) == ["second", "first"])
}

@Test func copyingTheSameTextAgainMovesItToTheTop() {
    var history = ClipboardHistory()
    history.record("a", types: text, at: at(0))
    history.record("b", types: text, at: at(10))
    history.record("a", types: text, at: at(20))
    #expect(history.items.map(\.text) == ["a", "b"])
    #expect(history.items.first?.copiedAt == at(20))
}

@Test func keepsOnlyTheLastTen() {
    var history = ClipboardHistory()
    for i in 1...12 { history.record("item \(i)", types: text, at: at(Double(i))) }
    #expect(history.items.count == 10)
    #expect(history.items.first?.text == "item 12")
    #expect(history.items.last?.text == "item 3")
}

@Test func passwordManagerCopiesAreSkipped() {
    var history = ClipboardHistory()
    history.record("hunter2", types: text + ["org.nspasteboard.ConcealedType"], at: at(0))
    #expect(history.items.isEmpty)
}

@Test func temporaryAndAutomaticCopiesAreSkipped() {
    var history = ClipboardHistory()
    history.record("123456", types: text + ["org.nspasteboard.TransientType"], at: at(0))
    history.record("auto", types: text + ["org.nspasteboard.AutoGeneratedType"], at: at(1))
    #expect(history.items.isEmpty)
}

@Test func blankCopiesAreSkipped() {
    var history = ClipboardHistory()
    history.record("   \n", types: text, at: at(0))
    #expect(history.items.isEmpty)
}

@Test func clearEmptiesTheHistory() {
    var history = ClipboardHistory()
    history.record("a", types: text, at: at(0))
    history.clear()
    #expect(history.items.isEmpty)
}

@Test func previewIsOneTrimmedLine() {
    let item = ClipboardItem(text: "  first line\nsecond line  ", copiedAt: at(0))
    #expect(item.preview == "first line second line")
}

@Test func ageReadsLikeMinutesAgo() {
    #expect(ClipboardItem.age(from: at(0), to: at(20)) == "now")
    #expect(ClipboardItem.age(from: at(0), to: at(4 * 60 + 10)) == "4m")
    #expect(ClipboardItem.age(from: at(0), to: at(2 * 3600 + 5)) == "2h")
}

@Test func copiedFilesAreSkipped() {
    // Finder puts the file's name on the clipboard as text too; that isn't a text copy.
    var history = ClipboardHistory()
    history.record("Report.pdf", types: ["public.file-url"] + text, at: at(0))
    #expect(history.items.isEmpty)
}

@Test func hugeCopiesAreSkipped() {
    var history = ClipboardHistory()
    history.record(String(repeating: "x", count: 1_000_001), types: text, at: at(0))
    #expect(history.items.isEmpty)
}

@Test func copiesFromAnotherDeviceAreSkipped() {
    // Universal Clipboard: the text still has to come over the network when read.
    #expect(ClipboardHistory.shouldRead(types: text + ["com.apple.is-remote-clipboard"]) == false)
}

@Test func onlyPlainLocalTextIsRead() {
    #expect(ClipboardHistory.shouldRead(types: text))
    #expect(ClipboardHistory.shouldRead(types: text + ["org.nspasteboard.ConcealedType"]) == false)
    #expect(ClipboardHistory.shouldRead(types: ["public.file-url"] + text) == false)
}

@Test func previewOfALongCopyIsShort() {
    let item = ClipboardItem(text: String(repeating: "word ", count: 10_000), copiedAt: at(0))
    #expect(item.preview.count <= 300)
}

@Test func theSameTextCopiedTwiceKeepsOneItem() {
    var history = ClipboardHistory()
    history.record("a", types: text, at: at(0))
    let firstID = history.items[0].id
    history.record("a", types: text, at: at(5))
    #expect(history.items.count == 1)
    #expect(history.items[0].id != firstID)   // a fresh row, so the list animates it to the top
}
