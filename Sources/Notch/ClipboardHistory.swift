import Foundation

struct ClipboardItem: Equatable, Identifiable {
    let text: String
    let copiedAt: Date
    var id: String { text }

    /// One line for the list: whitespace and line breaks collapsed to single spaces.
    var preview: String {
        text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }

    /// "now" under a minute, then "4m", then "2h".
    static func age(from copied: Date, to now: Date) -> String {
        let minutes = Int(now.timeIntervalSince(copied) / 60)
        if minutes < 1 { return "now" }
        if minutes < 60 { return "\(minutes)m" }
        return "\(minutes / 60)h"
    }
}

/// Recent text copies, newest first. Kept in memory only.
struct ClipboardHistory {
    static let limit = 10
    /// Pasteboard types apps use to say "don't keep this" (nspasteboard.org): passwords, one-time codes, automatic copies.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    /// Copied files also carry their names as text; those aren't text copies.
    static let fileTypes: Set<String> = ["public.file-url"]

    private(set) var items: [ClipboardItem] = []

    mutating func record(_ text: String, types: [String], at date: Date) {
        guard Self.privateTypes.isDisjoint(with: types), Self.fileTypes.isDisjoint(with: types),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text, copiedAt: date), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    mutating func clear() { items = [] }
}
