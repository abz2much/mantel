import Foundation

struct ClipboardItem: Equatable, Identifiable {
    let text: String
    let copiedAt: Date
    /// A fresh ID each time something is copied, cheap to compare however long the text is.
    let id = UUID()

    /// One line for the list, built from the start of the text only so huge copies stay fast:
    /// whitespace and line breaks collapse to single spaces.
    var preview: String {
        String(text.prefix(300)).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }

    /// "now" under a minute, then "4m", then "2h".
    static func age(from copied: Date, to now: Date) -> String {
        let minutes = Int(now.timeIntervalSince(copied) / 60)
        if minutes < 1 { return "now" }
        if minutes < 60 { return "\(minutes)m" }
        return "\(minutes / 60)h"
    }
}

/// Recent text copies, newest first. Kept in memory only.
struct ClipboardHistory {
    static let limit = 10
    /// Bigger copies (a log, a data dump) aren't kept: they'd hold memory and slow the list.
    static let maxCharacters = 1_000_000
    /// Types that mean "don't read this": apps marking a copy private or temporary (nspasteboard.org),
    /// such as passwords, one-time codes and automatic copies; copied files (their names come as text
    /// too); and copies from another device, whose text would have to come over the network.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "public.file-url",
        "com.apple.is-remote-clipboard",
    ]

    private(set) var items: [ClipboardItem] = []

    /// Checked before the text is read, so a password is never even pulled into memory.
    static func shouldRead(types: [String]) -> Bool {
        skippedTypes.isDisjoint(with: types)
    }

    mutating func record(_ text: String, types: [String], at date: Date) {
        guard Self.shouldRead(types: types),
              text.count <= Self.maxCharacters,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text, copiedAt: date), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    mutating func clear() { items = [] }
}
